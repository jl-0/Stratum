"""Write the EMIT-10 groupings - one class map per Tetracorder group - and the colour table the
demonstration contenders share.

    pixi run python examples/emit-cm-demo-sites/make_emit10.py \
        ../EMIT-Data-Resources/data/mineral_grouping_matrix_20230503.csv

Writes, beside this script:

    classes/emit10-g1.yaml   group-1 constituents -> goethite / hematite / other
    classes/emit10-g2.yaml   group-2 constituents -> the eight group-2 EMIT-10 minerals / mixed / other
    colors-emit10.yaml       colors-usgs-1995.yaml plus one colour per EMIT-10 class

The matrix is the EMIT L2B mineral grouping matrix: one row per constituent of the product's
294-entry class table, with a fraction per EMIT-10 mineral (the same file `emit-sds-l2b/data/`
carries; the two copies differ only in line endings). A constituent's class is the EMIT-10
mineral with the LARGEST positive fraction. 25 constituents are mixtures that reach two or three
minerals; when two minerals tie exactly the constituent is `mixed`. Every mixture is listed in a
comment beside its member so the rule can be overridden by editing this script, never the output.
A constituent with no positive fraction - a non-EMIT-10 mineral, vegetation, a man-made material,
or one of the ten the matrix marks -1 (a relative excluded on purpose, e.g. nacrite) - is `other`.

Two pairs of rows are identical in every attribute the granule's table carries (104/108,
Plastic_PETE; 180/181, Buddingtonite+Na-Mont), so no member can name one of them: they are left
out and reach `other` through `unmapped`. For the buddingtonite pair that overrides its 0.1
montmorillonite fraction - the feldspar dominates.

Class ids are shared by both files (1 calcite ... 10 vermiculite, 11 mixed, 12 other), so an id
means the same mineral in either group. Members are matched on (library, record, group), the
attributes the granule's own /mineral_metadata carries, never on the positional index.
"""
import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EMIT10 = ["Calcite", "Chlorite", "Dolomite", "Goethite", "Gypsum", "Hematite",
          "Illite+Muscovite", "Kaolinite", "Montmorillonite", "Vermiculite"]
SLUG = {m: m.lower().replace("+", "-") for m in EMIT10}
IDS = {SLUG[m]: i + 1 for i, m in enumerate(EMIT10)} | {"mixed": 11, "other": 12}
COLOURS = {                       # group colours follow the 1995 key where it has one
    "calcite": [150, 110, 80], "dolomite": [200, 160, 120], "chlorite": [60, 255, 0],
    "goethite": [255, 213, 0], "hematite": [255, 60, 0], "gypsum": [255, 60, 255],
    "illite-muscovite": [0, 200, 200], "kaolinite": [255, 255, 0],
    "montmorillonite": [0, 105, 255], "vermiculite": [185, 120, 255],
    "mixed": [200, 200, 200], "other": [100, 100, 100],
}

rows = list(csv.DictReader(Path(sys.argv[1]).open(newline="")))
assert len(rows) == 294, f"expected the 294-row V001 matrix, got {len(rows)}"
seen: dict[tuple[str, int, int], int] = {}
for r in rows:
    k = (r["Library"], int(r["Record"]), int(r["Group"]))
    seen[k] = seen.get(k, 0) + 1
AMBIGUOUS = {k for k, n in seen.items() if n > 1}


def classify(row: dict[str, str]) -> tuple[str, str]:
    """(class name, comment) for one constituent."""
    fr = {m: float(row[m]) for m in EMIT10 if row[m].strip() and float(row[m]) > 0}
    if not fr:
        neg = [m for m in EMIT10 if row[m].strip() and float(row[m]) < 0]
        return "other", (f"  [{neg[0]} -1 in the matrix]" if neg else "")
    top = max(fr.values())
    winners = [m for m, v in fr.items() if v == top]
    note = ("  [mixture: " + ", ".join(f"{m} {v:g}" for m, v in fr.items()) + "]"
            if len(fr) > 1 else "")
    return ("mixed" if len(winners) > 1 else SLUG[winners[0]]), note


for group in (1, 2):
    members: dict[str, list[str]] = {}
    for r in rows:
        if int(r["Group"]) != group:
            continue
        if (r["Library"], int(r["Record"]), group) in AMBIGUOUS:
            continue                  # unaddressable by attribute: reaches `other` via unmapped
        name, note = classify(r)
        members.setdefault(name, []).append(
            f"      - {{library: {r['Library']}, record: {int(r['Record'])}, group: {group}}}"
            f"   # {int(r['Index']):3d} {r['Name']}{note}")
    order = sorted(members, key=IDS.__getitem__)
    lines = [
        f"# emit10-g{group}: group-{group} Tetracorder constituents grouped into the EMIT-10 minerals.",
        "#",
        "# GENERATED by make_emit10.py from the EMIT L2B mineral grouping matrix",
        "# (mineral_grouping_matrix_20230503.csv). Do not edit by hand: change the rule there.",
        "# A constituent belongs to the EMIT-10 mineral with its largest fraction; an exact tie is",
        "# `mixed`; a constituent reaching no EMIT-10 mineral is `other`. Ids are shared with the",
        f"# other group's file, so an id names the same mineral in both.",
        "#",
        f"name: emit10-g{group}",
        "version: 1",
        "match_on: [library, record, group]",
        "unmapped: other            # rows no member can address by attribute (see make_emit10.py)",
        "classes:",
    ]
    for name in order:
        lines += [f"  - id: {IDS[name]}", f"    name: {name}",
                  f"    members:                        # {len(members[name])} constituent(s)"]
        lines += members[name]
    out = HERE / "classes" / f"emit10-g{group}.yaml"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(out.name, {n: len(v) for n, v in sorted(members.items(), key=lambda kv: IDS[kv[0]])})

base = (HERE / "colors-usgs-1995.yaml").read_text().rstrip("\n").splitlines()
header = [ln for ln in base if ln.startswith("#")]
body = [ln for ln in base if not ln.startswith("#")]
lines = [
    "# colors-usgs-1995.yaml plus the EMIT-10 classes of classes/emit10-g{1,2}.yaml.",
    "# GENERATED by make_emit10.py; do not edit by hand.",
    "#",
    *header,
    "#",
    "# EMIT-10 classes:",
    *[f'"{n}": {c}' for n, c in COLOURS.items()],
    "#",
    "# EMITL2BMIN.001 classes (the 1995 table):",
    *body,
]
(HERE / "colors-emit10.yaml").write_text("\n".join(lines) + "\n")
print("colors-emit10.yaml", len(COLOURS), "+", len(body))
