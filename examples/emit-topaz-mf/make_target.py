"""Write a matched-filter target spectrum from a specpr spectral library into stratum_emit.

    pixi run python examples/emit-topaz-mf/make_target.py \
        ../spectroscopy-tetracorder/sl1-usgs-new/library06.conv/s06emitc 5040 \
        ../tetracorder-lite/tetrapy/conv/specpr.py \
        plugins/stratum-emit/src/stratum_emit/targets/topaz-mt-antero-5.csv

Record 5040 of `s06emitc` is "Topaz Mt._Antero_#5", the USGS splib06 spectrum convolved to the
EMIT 285 channels - the entry Tetracorder 6.00a identifies topaz with and EMIT L2B index 239.
USGS spectral library data is public domain. The reader is loaded from its file because importing
the `tetrapy` package pulls in its CLI dependencies.
"""
import importlib.util
import sys
from pathlib import Path

import numpy as np

lib, recno, reader, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], Path(sys.argv[4])
spec = importlib.util.spec_from_file_location("specpr", reader)
specpr = importlib.util.module_from_spec(spec)
spec.loader.exec_module(specpr)

f = specpr.SpecprFile.open(lib)
rec = f.record(recno)
refl = np.asarray(f.read_spectrum(recno), dtype=np.float64)
wl = np.asarray(f.read_spectrum(rec.irwav), dtype=np.float64) * 1000.0   # um -> nm
good = np.isfinite(refl) & (refl > -1e30) & np.isfinite(wl)
lines = [f"# {rec.title.strip()}",
         f"# specpr record {recno} of {Path(lib).name}; wavelengths from record {rec.irwav}",
         "# USGS Digital Spectral Library splib06 - public domain",
         "# generated by examples/emit-topaz-mf/make_target.py; do not edit by hand",
         "wavelength_nm,reflectance"]
lines += [f"{w:.4f},{r:.6f}" for w, r in zip(wl[good], refl[good])]
out.write_text("\n".join(lines) + "\n")
print(f"{good.sum()} channels -> {out}")
